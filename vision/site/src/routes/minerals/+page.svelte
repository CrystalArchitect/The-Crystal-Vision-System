  <section class="chapter node" style="--node:var(--blue)">
    <h2>Kiln, SX, magnet</h2>
    <p>
      The kiln is not a metaphor. At Kalgoorlie the rare earth concentrate is mixed with
      concentrated sulphuric acid and cracked at high temperature in a rotating kiln about 110
      metres long and 6 metres high — one of the largest in Australia. That bake converts rare earth
      phosphate minerals to rare earth sulphate. The sulphate is leached, and the solution is
      neutralised to mixed rare earth carbonate. That MREC can travel. The rock, at that point, has
      become chemistry.
    </p>
    <p>
      Solvent extraction is the plant that follows. Two liquid phases, organic and aqueous, run in
      counter-current trains. The mixed carbonate is split into groups and then into individual
      elements. It is long, wet, tightly controlled work: mixer-settlers in series, not a press
      conference. Lynas still does this step at LAMP in Gebeng. That is the honest current map.
      Naming it is not an attack on the company; it is a statement of where the hard plant sits.
    </p>
    <p>
      After separation, oxides are reduced to metal and alloyed as neodymium-iron-boron. The alloy
      is pressed and sintered into the magnet. For motors that run hot, grain-boundary diffusion
      then coats the sintered magnet with a thin heavy-rare-earth source — usually dysprosium or
      terbium — and heat-treats it so those metals travel along the grain boundaries instead of
      being wasted through every grain. Coercivity rises. Remanence mostly holds. The magnet becomes
      the part a wind turbine, an electric motor, or a defence system actually specifies.
    </p>
    <p>
      That is why building here is a processing sentence, not a mining sentence. Trades live on the
      kiln, the SX hall, the metal furnace, and the magnet press. If those stay offshore, Australia
      remains the quarry with a good port.
    </p>
  </section>

  <section class="chapter node" style="--node:var(--silver)">
    <h2>What this page does not say</h2>
    <ul>
      <li>
        <strong>It does not select a berth.</strong> No town, no tenement, and no TerAustralis
        kiln is announced here. Geography under exploration stays on the proposal site, labelled as
        exploration.
      </li>
      <li>
        <strong>It does not sell a menu.</strong> This is one dish: keep processing on this
        continent so the magnet is made where the ore was dug. Software, mythos, and other doors of
        this archive are not this claim.
      </li>
      <li>
        <strong>It does not treat a framework as a plant.</strong> The October 2025 United
        States–Australia instrument names mining and processing. Until the trains are poured, the
        gap the IEA measured remains the gap.
      </li>
      <li>
        <strong>Lynas, IEA, Geoscience Australia and AFR names are nominative.</strong> Those
        marks belong to their owners. They are used here as the public record of a kiln, a report,
        an export total, and a newspaper.
      </li>
    </ul>
