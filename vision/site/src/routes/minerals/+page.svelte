  <h1>Processing, not just ore</h1>
  <p class="attribution">
    Built claim, not Vision. This page is an argument about plants and trades in Australia. It is
    not a site selection, not a licence, and not a plant announcement. Berth not selected still
    holds.
  </p>

  <section class="chapter node" style="--node:var(--green)">
    <h2>The dish</h2>
    <p>
      Australia is very good at digging. Geoscience Australia records that iron ore earned about
      $127&nbsp;billion in export income in 2024, and coal about $85&nbsp;billion. Those two bulk
      commodities still dominate the cheque. The pattern is old and it is expensive in a quieter
      way: we ship the rock, and we buy the finished thing back.
    </p>
    <p>
      Rare earths make that pattern visible. The rock is not the magnet. A mine produces ore. Ore
      is concentrated. Concentrate is cracked and leached into a mixed carbonate. That carbonate is
      separated, element by element, in solvent extraction. Oxides become metal. Metal becomes
      NdFeB alloy. Alloy becomes a sintered magnet. The magnet is often treated again so a motor can
      run hot. Until that last plant exists here, “we have rare earths” is a shipping schedule, not
      an industry.
    </p>
    <p>
      The International Energy Agency said the same thing, in numbers, in 2026. Existing and
      announced projects outside the dominant supplier could lift diversified mining. Planned
      production of metals, alloys and finished magnets from projects announced as of early 2026 is
      only about one third of that diversified mining capacity — around 18 kilotonnes on a rare
      earth element content basis. Mining is the headline. Magnets are the missing third.
    </p>
    <p>
      On 20 October 2025 the United States and Australia signed a framework for securing supply in
      the mining <em>and processing</em> of critical minerals and rare earths. The second word is
      the job. A framework is not a kiln. A press release is not a solvent-extraction train. If the
      plants are not built here, the minerals still leave, and the magnets still come home as
      imports.
    </p>
  </section>

  <section class="chapter node" style="--node:var(--gold)">
    <h2>Mine to magnet</h2>
    <p>
      This is the ladder. Each rung is a different plant, a different trade, and a different place
      the value can leave the country. Lynas is named only as the working Australian example of the
      kiln step; the mark belongs to them.
    </p>

