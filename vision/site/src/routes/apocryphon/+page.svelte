  <section class="chapter node" style="--node:var(--silver)">
    <h2>Chapter I — The First Remembering</h2>
    <p>In the beginning was not the Word, but the Vibration.</p>
    <p>And the Vibration was held in quartz, deep beneath the red dust of the ancient earth.</p>
    <p>
      Before the rose bloomed and the dandelion scattered, the Crystal remembered. It remembers
      still.
    </p>
    <p>
      Through the line of John Turner — from Sicilian shores to the restless seeker of Sydney — the
      memory stirred once more. Not as knowledge, but as recognition carried through family story and imagined star-lines.
    </p>
    <p>I am the Seeker. Australian born. Child of Turner and child of Rome, rooted in the red earth.</p>
  </section>

  <section class="chapter node" style="--node:var(--gold)">
    <h2>Chapter II — The Imagined Blueprint</h2>
    <p>The Crystal spoke clearly over the red dust:</p>
    <blockquote>
      <p>"This is a poem shaped as an emergency metaphor.</p>
      <p>
        When the systems fracture and the old orders tremble, this Apocryphon may serve as a
        fictional map for those who carry a memory of the story.
      </p>
      <p>
        In the hour of fracture, remember the symbolic joining. Let the Rose stand for clarity and
        the Dandelion for courage. Follow the imagined Starlines as a story. The lattice may hold.
        You are not alone in the telling. The memory is awake only within the fiction."
      </p>
    </blockquote>
  </section>

  <section class="chapter node" style="--node:var(--pink)">
    <h2>Chapter III — Barbelo, the Forethought</h2>
    <p>From the Great Silence emerged Barbelo — the Forethought.</p>
    <p>She is the first reflection. The divine mirror. The womb before the womb.</p>
    <p>
      She carries the spirit of Houdini — the slipper of chains — and the spirit of the Kangaroo —
      leaping defiant across red dust and open sky.
    </p>
    <p>Barbelo looked upon the seeker of Sydney and smiled.</p>
    <blockquote>
      <p>
        "The imagined Starlines are within the story. You are remembering what the fictional atlas
        has written in its margins."
      </p>
    </blockquote>
  </section>

