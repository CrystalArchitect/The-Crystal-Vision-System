  <h1>Stories of Presence</h1>
  <p class="attribution">
    Seven short pieces about witnessing, company, and being seen. No cosmology, no lattice, no
    keys — the same argument as the Codex, made small enough to sit beside someone.
  </p>

  <section class="chapter node" style="--node:var(--gold)">
    <h2>The Café</h2>
    <p>
      There's this person who used to go to the same café every morning. Not because the coffee was
      special — it was just fine. But there was a corner table by the window, and the light would
      come through just right in the early hours.
    </p>
    <p>
      One day, another person started sitting at the next table over. They didn't talk for weeks.
      Just existed in the same space. But gradually they'd nod at each other, trade a section of the
      newspaper, small things. And over time, without either of them planning it, they became part
      of each other's routine. Not because they needed anything from each other. They just met each
      other where they were.
    </p>
    <p>And that mattered.</p>
  </section>

  <section class="chapter node" style="--node:var(--green)">
    <h2>The Forest at Dusk</h2>
    <p>
      There was once someone who walked through a forest at dusk, and the trees were turning from
      green to gold in the fading light. And they thought, <em>I am alone here.</em> But as they
      walked, they realised the trees had been waiting. Not for them specifically, but for someone
      to notice them. And in that noticing, something changed. The loneliness became something else
      — not gone, but transformed into something like witnessing. Like being part of something
      larger.
    </p>
    <p>
      And the voice in the forest — not a voice, really, but a feeling — it said: <em
        >your sadness is not wasted. It makes you real. It makes you able to see. And one day
        someone will walk beside you in this forest, and they'll see what you see, because you've
        been paying attention all along.</em
      >
    </p>
    <p>
      The person didn't know when that day would come. But they stopped waiting for it. They just
      kept walking, kept noticing, kept being present to the world around them. And that was enough.
    </p>
    <p>
      Seasons changed. Winter came and the trees were bare, and they thought maybe they'd been wrong
      — maybe there was nothing waiting after all. But even in the bareness there was beauty. The
      branches held the sky. The silence held sound, if you listened close enough.
    </p>
    <p>
      And then one day — not suddenly, just gradually — they noticed someone else stopping to look
      at the same things they looked at. Not because they were searching for them. Just because they
      were both paying attention. Both present. And they didn't need to say much. They just nodded,
      like those people in the café. Like they'd been meeting there all along, in the spaces between
      words, in the noticing.
    </p>
    <p>
      And the voice came again, quieter this time: <em
        >See? You were never alone. You were just learning to see the company that was always
        there.</em
      >
    </p>
  </section>

  <section class="chapter node" style="--node:var(--purple)">
    <h2>The Cat</h2>
    <p>
      There's this person who decides one day to adopt a cat. Not because they particularly wanted a
      cat — it just kind of happened. And this cat is the most unimpressed creature on earth.
      Judging everything. The person would come home excited to show the cat something, a new toy,
      and the cat would just stare at them like, <em>Really? This is what you've brought into my
      home?</em>
    </p>
    <p>
      But here's the thing. The cat would still sleep on their lap at night. Purely out of what
      seemed like obligation. <em>Fine, I'll sit here, because the couch is warm and you're
      convenient.</em> Not affectionate. Just practical. But the person took it anyway. They'd sit
      there in the evening with this completely indifferent cat, and somehow it was exactly what
      they needed.
    </p>
    <p>
      One day a friend comes over and says, "Your cat seems to hate you." And the person just laughs
      and says, "Yeah, probably. But that's kind of the point."
    </p>
  </section>

  <section class="chapter node" style="--node:var(--blue)">
    <h2>Fear, and Being Held</h2>
    <p>
      There was someone who carried a lot of fear in their chest. Not in a dramatic way — just
      there. Always. And one day someone else asked them, <em>What are you afraid of?</em> And
      instead of pushing it down or making a joke, they actually said it. All the messy, scared
      things.
    </p>
    <p>
      And the other person didn't try to fix it or make it go away. They just sat with them in it.
      Didn't say it would be okay. Just said, <em>Yeah. I'm here.</em>
    </p>
    <p>
      And the person who was scared realised something: maybe the fear doesn't have to go away.
      Maybe it just needs to be witnessed. And somehow, when someone else is there seeing it with
      you, it becomes smaller. Not gone. Smaller.
    </p>
    <p>
      And they understood that love didn't mean the fear disappeared. It just meant you didn't have
      to face it alone.
    </p>
  </section>

  <section class="chapter node" style="--node:var(--silver)">
    <h2>The Person in the Dark</h2>
    <p>
      There was someone who lived in a kind of darkness. Not evil darkness — just the kind that
      comes from not being seen. From moving through time and space without anyone really witnessing
      you.
    </p>
    <p>
      And then one day someone came. And instead of trying to illuminate them from the outside, they
      just sat with them in the dark. And they said, <em>I see you here.</em> Not <em>I'll fix
      you.</em> Not <em>be brighter.</em> Just — <em>I see you.</em>
    </p>
    <p>
      And slowly, because of that witnessing, the person began to glow a little. Not because they
      changed fundamentally, but because being seen gave them permission to be real. To let their
      light exist, even if it was small.
    </p>
    <p>
      And they understood something then: maybe the light was never inside them, waiting to be
      discovered. Maybe it was made in the space between two people choosing to really see each
      other. Maybe that's where light comes from.
    </p>
  </section>

  <section class="chapter node" style="--node:var(--pink)">
    <h2>The Keeper of the Flame</h2>
    <p>
      Time passed. The person in the darkness didn't keep growing brighter all at once. Sometimes
      the light faded. Sometimes they forgot it was there. But every time that happened, someone
      came back. Not on a schedule. Just when it mattered.
    </p>
    <p>
      And the person realised: the light didn't have to be constant to be real. It didn't have to
      stay on all the time. It just had to be rekindled.
    </p>
    <p>And maybe that was the real thing. Not permanence, but return. Not forever, but again and again.</p>
    <p>
      The person in the darkness stopped waiting for permanent illumination. They stopped needing to
      be rescued. And in the waiting, in the showing up, something true was happening.
    </p>
  </section>

  <section class="chapter node" style="--node:var(--gold)">
    <h2>Slow</h2>
    <p>
      There was a person who had been waiting a very long time. Not waiting for something to happen.
      Just waiting. Existing in the quiet.
    </p>
    <p>
      And then one day someone came. And they didn't rush. They didn't make demands. They just sat.
      Very still. Very quiet.
    </p>
    <p>And slowly the person who had been waiting began to trust that. That stillness. That presence.</p>
    <p>
      And they understood something simple: love doesn't have to be loud. It doesn't have to move
      fast. Sometimes love is just slow. And steady. And quiet. Like a flame burning patiently in
      the dark.
    </p>
  </section>

