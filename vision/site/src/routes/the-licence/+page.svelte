  <h1>The licence</h1>
  <p class="attribution">
    Built claim, not Vision. This page is about Australia’s civil nuclear power prohibitions and a
    public US demonstration path with an Australian founder. It is not a product page for that
    company, not a berth claim, and not a licence application.
  </p>

  <section class="chapter node" style="--node:var(--green)">
    <h2>What happened</h2>
    <p>
      Bobby Gallagher, an Australian engineer, is CEO and co-founder of Houston-based Deployable
      Energy. Their Unity Nuclear Battery is a ~1 megawatt-class transportable microreactor:
      factory-style manufacture, roughly a five-year refuel cycle, conventional logistics. The core
      was moved to Idaho National Laboratory on a pickup; the full package is shipping-container
      scale.
    </p>
    <p>
      In late June 2026 the unit reached criticality at INL on a compressed timeline (company and
      DOE-adjacent reporting put kickoff-to-criticality around 150 days), under the US advanced
      reactor demonstration push. White House and Energy Department photo ops with Gallagher are on
      the public record.
    </p>
  </section>

  <section class="chapter node" style="--node:var(--gold)">
    <h2>What is banned here</h2>
    <p>
      Australia’s federal framework still prohibits licensing civil nuclear power plants. Under the
      Australian Radiation Protection and Nuclear Safety Act, the regulator cannot grant a licence
      for construction or operation of a nuclear power plant (alongside fuel fabrication,
      enrichment, and reprocessing). Related Environment Protection and Biodiversity Conservation
      limits and state prohibitions reinforce the same wall.
    </p>
    <p>
      Research and medical nuclear work continues. Naval nuclear pathways for AUKUS are a separate
      legislative track. Neither is a civil power-plant licence for a Deployable-class unit on
      Australian soil.
    </p>
  </section>

  <section class="chapter node" style="--node:var(--blue)">
    <h2>How to hold the chrome</h2>
    <p>
      “Mass-produced in months” and “swap-and-go gas bottle” are marketing compression. Criticality
      is not a sold-and-swapped commercial fleet. Company materials point commercial lead times
      later than the pilot sprint.
    </p>
    <p>
      “Fastest and lowest-cost reactor build in American history” is advocacy ranking, not a settled
      ledger. Exact viral Trump quotes should be treated as paraphrase until pinned to a primary.
      The company and demo path are United States-based; do not over-claim that Lucas Heights built
      the commercial unit.
    </p>
  </section>

  <section class="chapter node" style="--node:var(--silver)">
    <h2>The sentence</h2>
    <p>
      Australian talent. Australian ban. US criticality demo. The regulatory sentence is the story.
      Steal the factory-product constraint — product, not decade-project. Drop the gas-bottle
      mythology until one has been sold and swapped.
    </p>
    <p><strong>Talent isn’t the bottleneck. The licence is.</strong></p>
  </section>

