  <section class="chapter node" style="--node:var(--green)">
    <h2>The rocket is not the gate</h2>
    <p>
      Starship architecture assumes Mars already has carbon dioxide in the air and water ice in
      the ground. Sabatier chemistry plus electrolysis turns that into methane and oxygen so the
      ship can leave again. Orbit refuel gets you off Earth heavy. Surface propellant gets you free
      of Earth. That is the real gate.
    </p>
  </section>

  <section class="chapter node" style="--node:var(--gold)">
    <h2>Not “red dust chemistry”</h2>
    <p>
      Return fuel is atmosphere and ice. The rust is the factory floor — hematite-rich fines,
      heat, isolation, abrasion that eats seals and bearings — and a later feedstock for metal and
      oxygen by reduction. Confusing the two sentences is how the argument slips.
    </p>
  </section>

  <section class="chapter node" style="--node:var(--blue)">
    <h2>That floor already exists</h2>
    <p>
      Pilbara and inland arid Australia are among the best terrestrial stand-ins: iron-rich red
      dust, heat, isolation, high solar load. A Pilbara chert sample from Marble Bar flew on NASA
      Perseverance as a SuperCam calibration target — a geological postcard from Australia to Mars,
      not a claim that chert is propellant feedstock.
    </p>
    <p>
      Australian labs have already pulled iron metal out of Mars-regolith simulant under Mars-like
      conditions (CSIRO and Swinburne). That is oxide-to-metal ISRU on the research bench. It is
      not a claim that Pilbara mine feed was the paper’s feedstock.
    </p>
  </section>

