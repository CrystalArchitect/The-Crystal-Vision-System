  <section class="chapter node" style="--node:var(--green)">
    <h2>The mineral and the launch are already in the literature</h2>
    <p>
      Australian desks can download a long ASPI critical-minerals report. They can download a
      separate argument that AUKUS still needs a space pillar, including launch infrastructure.
      Both are free. Both are real. They are two tracks. A desk that has to move this month is
      left to join them.
    </p>
    <p><strong>Named Pathway Brief</strong> is that join, on one page.</p>
    <p>
      It is for Australian and AUKUS desks that already read ASPI, USSC, and allied minerals or
      space papers, and have to act before the next long report cycle.
    </p>
    <p>
      The hole, stated once: "ASPI and allied shops publish AUKUS space (including launch) and
      critical minerals as two separate free long-form tracks; none of the catalogues we can see
      offers a fast one-pager that joins a named Australian mineral pathway to launch capability
      for a desk that has to act before the next report cycle."
    </p>
  </section>

  <section class="chapter node" style="--node:var(--gold)">
    <h2>What you already have for $0</h2>
    <p>
      ASPI publishes AUKUS-and-minerals as one research track and AUKUS-and-space as another.
      James Palmer's Strategist piece, <em>AUKUS needs a third pillar: space</em> (27 June 2025),
      argues for launch infrastructure and does not treat minerals. Ben Halton and Kim Beazley's
      ASPI report on AUKUS and critical minerals does not close on a named pathway to a pad.
    </p>
    <p>
      USSC publishes economic-security and supply-chain-resilience papers on minerals, and a
      separate paper on space strengths for the alliance — same centre, two tracks. Consultancies
      and law firms (PwC, Norton Rose Fulbright) publish thought-leadership to sell retainers, not
      a standalone brief.
    </p>
    <p>None of those catalogues, as checked, sells a fast one-pager that traces one Australian mineral to launch capability for one desk. Free long-form is not the problem. Timing and join-up are.</p>
  </section>

  <section class="chapter node" style="--node:var(--blue)">
    <h2>What the brief is</h2>
    <p>
      One page. One named Australian mineral — NdPr, rutile, nickel, or whatever the desk
      actually has on its list this month. Not a tour of the critical-minerals strategy. Not
      "space" as a theme.
    </p>
    <p>
      One path: that mineral, through the industrial step that exists or does not exist in
      Australia, to a launch-relevant use a desk can name. Mining is not the end of the sentence.
      A slide titled "sovereign capability" is not the end of the sentence.
    </p>
    <p>Who is on the path. Who is not. What is missing. What can be done this month without waiting for the next institutional report cycle.</p>
    <p>Written for one desk. Readable in ten minutes. Used the same week.</p>
  </section>

